/**
 * @file  sd_update.h
 * @brief Оркестрация установки образа tft_app с microSD в неактивный слот.
 *
 * См. firmware/bootloader/PLAN.md, Фаза 3.
 */

#ifndef SD_UPDATE_H_
#define SD_UPDATE_H_

#include <stdbool.h>

/**
 * @brief Одна попытка: смонтировать SD, найти TFT_APP.BIN, при необходимости
 *        установить его в целевой слот (см. update_policy.h).
 *
 * Обычный режим (recovery_mode == false) пишет только в неактивный слот —
 * уже выбранный/загружаемый слот никогда не трогается. Recovery-режим
 * (Фаза 6b) — ослабленный gate: любой подписанный кандидат ставится в Slot A
 * безусловно, Slot Б стирается. Сам не вызывает boot_go()/
 * boot_select_and_jump() — решение "когда прыгать" остаётся за main.c,
 * которое обязано вызвать его ровно один раз за сессию питания (см.
 * slot_version.h о том, почему boot_go() нельзя звать повторно).
 *
 * Ничего не делает, если SD не вставлена (bsp_sd_is_inserted() == false) —
 * безопасно вызывать многократно, в т.ч. из цикла ожидания в main.c.
 *
 * @param downgrade_button_held  Состояние BSP_BUTTON_1, сэмплированное ОДИН РАЗ
 *        при старте (main.c, до медленной SD-инициализации) и защёлкнутое.
 *        true → разрешён форс. даунгрейд более старого подписанного образа
 *        (см. update_policy.h). Передаётся, а не читается здесь, чтобы жест
 *        "удержание при включении" ловился в предсказуемый ранний момент, а не
 *        через несколько секунд внутри run_update() (DEBUG_LOG_PHASE3_SD.md).
 *        Игнорируется при recovery_mode == true.
 * @param recovery_mode  Ослабленный version-gate (Фаза 6b) — см.
 *        update_policy_decide(). Решение "входить ли в recovery" принимает
 *        вызывающий код (recovery_decide(), recovery.h), не эта функция.
 *
 * @retval true   Кандидат успешно установлен и прошёл финальный крипто-гейт
 *                (slot_version_get() на целевом слоте) — в целевом слоте
 *                теперь новый валидный образ.
 * @retval false  Ничего не установлено (SD не вставлена/нет файла/skip) либо
 *                установка не удалась/кандидат отклонён — целевой слот не
 *                изменился относительно состояния до вызова.
 *
 * @pre bsp_qspi_init() уже вызван.
 */
bool sd_update_check(bool downgrade_button_held, bool recovery_mode);

#endif /* SD_UPDATE_H_ */
