/**
 * @file  crash_log.h
 * @brief Диагностика причины предыдущего сброса — крэш-запись, переживающая
 *        сброс ядра.
 *
 * ЗАЧЕМ: до этого модуля «сброс по watchdog», «переполнение стека задачи» и
 * HardFault выглядели на плате ОДИНАКОВО — немое зависание, через 10 с
 * добитое watchdog'ом (таймаут взводит загрузчик, см. bootloader/src/main.c).
 * Различить их без отладчика было нельзя, а лечатся они по-разному.
 *
 * КАК: запись живёт в секции `.noinit` (см. cmake/linker/..._app_slot.ld) —
 * вне диапазона, который обнуляет startup, а DTCM сохраняет содержимое через
 * сброс ядра. Хук/обработчик пишет причину и немедленно уходит в
 * `NVIC_SystemReset()`; после перезапуска bringup печатает её в лог.
 *
 * ДВА РЕЖИМА ЗАПИСИ — разница существенная:
 *   - crash_log_record_and_reset() — отказ В КОДЕ (HardFault, переполнение
 *     стека, malloc). Контекст враждебный, продолжать нельзя: пишем и
 *     сбрасываемся сами, не дожидаясь watchdog — цикл диагностики на стенде
 *     короче, причина в логе однозначна.
 *   - crash_log_record_stall() — задача перестала подавать признаки жизни
 *     (§3.7, heartbeat.h). Здесь сбрасываться САМИМ нечем и незачем: система
 *     формально работоспособна, отказала одна задача. Пишем причину и
 *     прекращаем кормить watchdog — сброс делает ОН, штатным путём, как и
 *     задумано аппаратной защитой. Запись переживает этот сброс и объясняет
 *     его на следующем старте.
 *
 * «Никто не кормил watchdog» отличается от всех них тем, что крэш-записи НЕТ,
 * а WDOG1->WRSR при этом показывает TOUT (см. bsp_wdog_reset_was_timeout()).
 */

#ifndef APP_CRASH_LOG_H_
#define APP_CRASH_LOG_H_

#include <stdbool.h>
#include <stdint.h>

/** Причина, записанная перед сбросом. */
typedef enum
{
    CRASH_CAUSE_NONE = 0, /**< записи нет — обычный старт             */
    CRASH_CAUSE_STACK_OVERFLOW, /**< vApplicationStackOverflowHook          */
    CRASH_CAUSE_HARDFAULT,      /**< HardFault_Handler                      */
    CRASH_CAUSE_MALLOC_FAILED,  /**< vApplicationMallocFailedHook           */
    CRASH_CAUSE_TASK_STALL, /**< наблюдаемая задача протухла (§3.7)     */
} crash_cause_t;

/**
 * @brief Записать причину и уйти в сброс. НЕ возвращается.
 *
 * Вызывается из хуков/обработчиков — контекст враждебный (возможно, ISR с
 * повреждённым стеком), поэтому внутри никакого форматирования и логирования:
 * только запись полей и `NVIC_SystemReset()`.
 *
 * @param cause     что случилось
 * @param p_name    имя задачи (может быть NULL) — копируется усечённо
 * @param pc        адрес инструкции (HardFault; иначе 0)
 * @param lr        LR на момент отказа (HardFault; иначе 0)
 */
void crash_log_record_and_reset(crash_cause_t cause, const char *p_name, uint32_t pc, uint32_t lr);

/**
 * @brief Записать «задача протухла» БЕЗ сброса (§3.7) — сброс сделает watchdog.
 *
 * Звать из супервизора (`input_poll_cb`), когда heartbeat_all_fresh() вернула
 * false. Контекст — демон программных таймеров со стеком 1 КБ, поэтому здесь
 * НЕТ и не должно быть ни одного `LOG_*` (vsnprintf там опасен, см.
 * docs/PERF_AND_HANG_INVESTIGATION.md): только запись полей.
 *
 * ИДЕМПОТЕНТНА: запоминает ПЕРВУЮ причину. Супервизор зовёт её каждые 5 мс всё
 * время до срабатывания watchdog — без этого свойства первичный диагноз
 * затёрли бы задачи, протухшие следом как ЛАВИНА от того же залипания.
 *
 * @param p_task   имя протухшей задачи (heartbeat_task_name())
 * @param p_where  «хлебная крошка» — где она залипла (heartbeat_breadcrumb())
 * @param age_ms   сколько мс не подавала признаков жизни
 */
void crash_log_record_stall(const char *p_task, const char *p_where, uint32_t age_ms);

/** Имя задачи в крэш-записи, байт. */
#define CRASH_NAME_MAX 16U

/** «Хлебная крошка» — свой, больший лимит: крошки соседних веток одной задачи
 *  различаются В КОНЦЕ строки, и общий лимит 16 съедал ровно различающую часть
 *  (найдено на HW-проверке §3.7). */
#define CRASH_WHERE_MAX 32U

/**
 * @brief Причина предыдущего сброса — СНЯТАЯ копия, пригодная для нескольких
 *        потребителей.
 *
 * Крэш-запись в `.noinit` — ресурс ОДНОКРАТНОГО потребления: тот, кто её
 * прочитал, обязан её погасить, иначе она припишет себя следующему сбросу.
 * Пока потребитель был один (лог), «прочитать и напечатать» совпадали. С
 * появлением загрузочного экрана (§3.10) потребителей стало двое — и если бы
 * каждый читал запись сам, второй не получил бы ничего. Ровно эта ошибка уже
 * случилась с `SRC->SRSR` в §3.8, повторять её не будем.
 *
 * Поэтому: снимаем ОДИН раз в структуру (crash_log_take_previous), дальше все
 * читают структуру.
 */
typedef struct
{
    bool valid; /**< была ли крэш-запись (false — её не было)      */
    crash_cause_t cause;
    uint32_t pc;                 /**< HardFault: PC. TASK_STALL: возраст heartbeat, мс */
    uint32_t lr;                 /**< HardFault: LR. Иначе 0                          */
    char name[CRASH_NAME_MAX];   /**< имя задачи                             */
    char where[CRASH_WHERE_MAX]; /**< крошка (TASK_STALL); иначе пусто      */
    bool wdog_timeout;           /**< WDOG1->WRSR: плату добил watchdog              */
} crash_info_t;

/**
 * @brief Снять причину предыдущего сброса и ПОГАСИТЬ запись.
 *
 * Звать РОВНО ОДИН раз, из bringup_task. Второй вызов вернёт `valid == false`
 * — запись уже погашена (это не ошибка, а контракт однократного потребления).
 *
 * `wdog_timeout` читается здесь же: `WDOG1->WRSR` погашения не требует
 * (read-only, самоочищается на каждый сброс), но логично собрать всю картину
 * в одном месте.
 */
void crash_log_take_previous(crash_info_t *p_out);

/**
 * @brief Напечатать снятую причину в лог. Не потребляет ничего.
 *
 * Звать после crash_log_take_previous() и ПОСЛЕ применения уровня логов
 * (§3.9) — иначе строка уйдёт в UART даже при выбранном «Выкл».
 */
void crash_log_report(const crash_info_t *p_info);

/**
 * @brief Короткое имя причины («TASK STALL», «HARDFAULT»…) — для лога и экрана.
 *
 * NULL, если причины не было: у загрузочного экрана это означает «строки про
 * сброс не выводить вовсе» (§3.10).
 */
const char *crash_log_cause_name(const crash_info_t *p_info);

#endif /* APP_CRASH_LOG_H_ */
