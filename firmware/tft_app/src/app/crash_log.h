/**
 * @file  crash_log.h
 * @brief Диагностика причины предыдущего сброса — крэш-запись, переживающая
 *        сброс ядра.
 *
 * ЗАЧЕМ: до этого модуля «сброс по watchdog», «переполнение стека задачи» и
 * HardFault выглядели на плате ОДИНАКОВО — немое зависание, через 10 с
 * добитое watchdog'ом (таймаут взводит загрузчик, см. bootloader/src/main.c).
 * Различить их без отладчика было нельзя, а лечатся они по-разному.
 *
 * КАК: запись живёт в секции `.noinit` (см. cmake/linker/..._app_slot.ld) —
 * вне диапазона, который обнуляет startup, а DTCM сохраняет содержимое через
 * сброс ядра. Хук/обработчик пишет причину и немедленно уходит в
 * `NVIC_SystemReset()`; после перезапуска bringup печатает её в лог.
 *
 * Немедленный сброс вместо ожидания watchdog — сознательно: цикл диагностики
 * на стенде короче (не надо ждать 10 с), и причина в логе однозначна.
 * «Никто не кормил watchdog» отличается от них тем, что крэш-записи НЕТ, а
 * WDOG1->WRSR при этом показывает TOUT (см. bsp_wdog_reset_was_timeout()).
 */

#ifndef APP_CRASH_LOG_H_
#define APP_CRASH_LOG_H_

#include <stdint.h>

/** Причина, записанная перед сбросом. */
typedef enum
{
    CRASH_CAUSE_NONE = 0, /**< записи нет — обычный старт             */
    CRASH_CAUSE_STACK_OVERFLOW, /**< vApplicationStackOverflowHook          */
    CRASH_CAUSE_HARDFAULT,      /**< HardFault_Handler                      */
    CRASH_CAUSE_MALLOC_FAILED,  /**< vApplicationMallocFailedHook           */
    CRASH_CAUSE_STARVATION, /**< задача-кормилец WDOG долго не получала CPU */
} crash_cause_t;

/**
 * @brief Отметиться «я жива» — из задачи, кормящей watchdog.
 *
 * Пара к crash_log_check_starvation(): детектор голодания живёт в демоне
 * программных таймеров (его нельзя выголодать — высший приоритет в системе) и
 * срабатывает РАНЬШЕ аппаратного watchdog, успевая записать, ЧЕМ была занята
 * система. Иначе сброс приходит молча (что и наблюдалось на стенде).
 */
void crash_log_feed_mark(void);

/**
 * @brief Проверить, не голодает ли кормилец. Звать из input_poll_cb.
 *
 * Если отметки нет дольше порога — записать CRASH_CAUSE_STARVATION вместе с
 * «хлебной крошкой» (где именно система залипла, см. crash_log_set_breadcrumb)
 * и сбросить плату. НЕ возвращается в этом случае.
 */
void crash_log_check_starvation(void);

/**
 * @brief Оставить «хлебную крошку»: строковый литерал с местом в коде.
 *
 * Ставится ПЕРЕД потенциально долгой операцией и снимается после. Пишется в
 * крэш-запись при детекте голодания — это и есть ответ на вопрос «кто держал
 * CPU». Литерал не копируется (только указатель), поэтому передавать строго
 * строковые константы.
 */
void crash_log_set_breadcrumb(const char *p_where);

/**
 * @brief Записать причину и уйти в сброс. НЕ возвращается.
 *
 * Вызывается из хуков/обработчиков — контекст враждебный (возможно, ISR с
 * повреждённым стеком), поэтому внутри никакого форматирования и логирования:
 * только запись полей и `NVIC_SystemReset()`.
 *
 * @param cause     что случилось
 * @param p_name    имя задачи (может быть NULL) — копируется усечённо
 * @param pc        адрес инструкции (HardFault; иначе 0)
 * @param lr        LR на момент отказа (HardFault; иначе 0)
 */
void crash_log_record_and_reset(crash_cause_t cause, const char *p_name, uint32_t pc, uint32_t lr);

/**
 * @brief Напечатать причину предыдущего сброса и очистить запись.
 *
 * Звать один раз из bringup_task ПОСЛЕ инициализации лога. Печатает:
 *   - крэш-запись, если она есть (и гасит её, чтобы не повторялась);
 *   - иначе «сброс по watchdog», если WDOG1->WRSR показывает TOUT — это как
 *     раз случай «задача-кормилец не получала CPU»;
 *   - иначе штатный старт.
 */
void crash_log_report_previous(void);

#endif /* APP_CRASH_LOG_H_ */
