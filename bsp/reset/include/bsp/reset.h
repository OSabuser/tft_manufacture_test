/*
 * bsp_reset — источник ПОСЛЕДНЕГО сброса МК (регистр SRC->SRSR).
 *
 * ЗАЧЕМ отдельный модуль, а не часть bsp_wdog: причина сброса — это System
 * Reset Controller, а не watchdog. bsp_wdog отвечает на один вопрос («был ли
 * это таймаут WDOG1», по своему WDOG1->WRSR); SRSR отвечает на общий — подача
 * питания, внешний вывод сброса, программный сброс, зависание ядра, отладчик,
 * перегрев.
 *
 * ДВА СВИДЕТЕЛЯ, не дубли. WDOG1->WRSR (bsp_wdog_reset_was_timeout()) и
 * SRC->SRSR — независимые регистры разных блоков; по watchdog они обязаны
 * сходиться, и расхождение само по себе диагностично.
 *
 * ПОРЯДОК ВЫЗОВА. bsp_reset_capture() читает SRSR, запоминает и ОЧИЩАЕТ
 * регистр. Очистка обязательна: биты залипают до явного сброса, и без неё со
 * второй перезагрузки они накапливаются — отчёт начинает врать. Обратная
 * сторона: после capture() исходный регистр пуст, поэтому звать её нужно
 * ровно один раз и как можно раньше в main(), а всем остальным читать
 * латч через bsp_reset_sources().
 *
 * Разбор маски (bsp_reset_source_name()) — ЧИСТАЯ функция без SDK и регистров,
 * живёт в отдельной единице трансляции и host-тестируется.
 */

#ifndef BSP_RESET_H
#define BSP_RESET_H

#include <stdint.h>

/* ── Источники сброса ────────────────────────────────────────────────────────
 *
 * Собственные флаги BSP, НЕ сырые биты SRSR: раскладка регистра — деталь
 * конкретного чипа, отображение живёт в reset.c. Набор ниже — то, что
 * MIMXRT1052 реально умеет различать (см. MIMXRT1052_features.h: отдельных
 * бит POR и LOCKUP у этого чипа НЕТ, см. два примечания ниже).
 */

#define BSP_RESET_SRC_NONE 0x00U

/** Подача питания / штатный старт (SRSR: ipp_reset_b, «power-up sequence»).
 *  ОТДЕЛЬНОГО бита POR у RT1052 нет — включение питания приходит сюда. */
#define BSP_RESET_SRC_POWER_UP (1U << 0)

/** Внешний вывод сброса, квалифицированный как холодный. */
#define BSP_RESET_SRC_USER_PIN (1U << 1)

/** Таймаут WDOG1 — тот самый, что взводит загрузчик. */
#define BSP_RESET_SRC_WDOG (1U << 2)

/** Таймаут WDOG3. */
#define BSP_RESET_SRC_WDOG3 (1U << 3)

/** ПРОГРАММНЫЙ сброс (NVIC_SystemReset/SYSRESETREQ) ЛИБО зависание ядра
 *  (lockup). У RT1052 это ОДИН бит на два совершенно разных события —
 *  отдельного бита LOCKUP нет. Различить их регистром невозможно: это делает
 *  крэш-запись `.noinit` (app/crash_log.h) — наш управляемый сброс её
 *  оставляет, зависание ядра нет. */
#define BSP_RESET_SRC_SW_OR_LOCKUP (1U << 4)

/** Сработала температурная защита. */
#define BSP_RESET_SRC_OVERHEAT (1U << 5)

/** Отладчик: HIGH-Z/EXTEST по JTAG. */
#define BSP_RESET_SRC_JTAG (1U << 6)

/** Отладчик: программный сброс через JTAG. */
#define BSP_RESET_SRC_JTAG_SW (1U << 7)

/** Central Security Unit. */
#define BSP_RESET_SRC_CSU (1U << 8)

/*
 * Зафиксировать источник последнего сброса и ОЧИСТИТЬ SRSR.
 *
 * Звать один раз, максимально рано в main() (регистр доступен сразу, тактов и
 * инициализации не требует). Повторный вызов — no-op: латч уже снят, а
 * регистр очищен, и второе чтение дало бы пусто.
 */
void bsp_reset_capture(void);

/*
 * Маска BSP_RESET_SRC_* последнего сброса. BSP_RESET_SRC_NONE — либо
 * bsp_reset_capture() не звали, либо регистр был пуст.
 *
 * Бит может быть не один: биты SRSR залипают, и если предыдущий образ (или
 * прошлая версия этого) регистр не чистил, накопится несколько. Именно
 * поэтому для лога есть bsp_reset_source_name() с приоритетом, а не
 * «первый попавшийся».
 */
uint32_t bsp_reset_sources(void);

/*
 * Сырое значение SRSR на момент capture() — для лога «как есть».
 *
 * Печатать вместе с разобранным именем: имя может огрубить (несколько
 * источников → одна строка), сырое значение не теряет ничего.
 */
uint32_t bsp_reset_raw(void);

/*
 * Человекочитаемая причина по маске — ЧИСТАЯ функция (без регистров и SDK,
 * host-тестируется).
 *
 * Если бит не один, возвращает САМЫЙ ИНФОРМАТИВНЫЙ: аварийные источники
 * (перегрев, watchdog, зависание) важнее штатных (подача питания), потому что
 * штатный бит может остаться от прошлого цикла, а аварийный означает событие.
 * Полную картину даёт bsp_reset_raw().
 *
 * Никогда не NULL: пустая маска → «неизвестен».
 */
const char *bsp_reset_source_name(uint32_t sources);

#endif /* BSP_RESET_H */
