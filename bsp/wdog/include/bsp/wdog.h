/*
 * bsp_wdog — аппаратный watchdog (WDOG1, MIMXRT1052).
 *
 * Назначение: аппаратный сброс МК по таймауту. Защищает от зависаний в
 * блокирующих вызовах, которые не возвращают управление в код приложения —
 * там, где программный watchdog (флаг + проверка в основном цикле) бессилен,
 * поскольку сам цикл не выполняется.
 *
 * Контракт: WDOG Enable (WDE) — write-once бит. После bsp_wdog_init() watchdog
 * нельзя выключить программно до следующего POR; он остаётся взведённым в
 * течение всей сессии питания, включая любую передачу управления внутри неё
 * (не только через ресет). Любой код, к которому управление переходит после
 * инициализации watchdog в этой же сессии, обязан периодически звать
 * bsp_wdog_refresh() не реже периода таймаута — иначе reset-loop. Под
 * отладчиком (SWD halt) watchdog приостанавливается (enableDebug=false), так
 * что пошаговая отладка не сбивается сбросами.
 */

#ifndef BSP_WDOG_H
#define BSP_WDOG_H

#include "bsp/status.h"

#include <stdbool.h>
#include <stdint.h>

/*
 * Взвести WDOG1 с таймаутом timeout_s секунд (аппаратно округляется до шага
 * 0.5 с: реальный таймаут = (2*timeout_s) * 0.5 c). Разумный диапазон 1..128.
 *
 * Побочно захватывает причину ПРЕДЫДУЩЕГО сброса (WDOG-таймаут vs прочее) для
 * bsp_wdog_caused_last_reset() — читать до/после безразлично, но делается тут.
 *
 * Вызывать один раз, как можно раньше в main() (после board_hw_init()).
 * Повторный вызов — no-op (WDE уже взведён).
 */
bsp_status_t bsp_wdog_init(uint32_t timeout_s);

/*
 * "Погладить" watchdog — сбросить счётчик таймаута. Дёшево; безопасно звать
 * даже если WDOG не взведён (запись refresh-последовательности безвредна).
 * Звать только в точках РЕАЛЬНОГО прогресса, НЕ перед блокирующими вызовами,
 * от зависания в которых watchdog и защищает.
 */
void bsp_wdog_refresh(void);

/*
 * true, если ПОСЛЕДНИЙ сброс МК был вызван таймаутом WDOG (а не power-on /
 * software / прочим). Валидно после bsp_wdog_init(). Для диагностики: показать
 * технологу через USB-CDC, что плата восстановилась после зависания.
 */
bool bsp_wdog_caused_last_reset(void);

/* true после успешного bsp_wdog_init(). */
bool bsp_wdog_is_armed(void);

/* Сконфигурированный таймаут в секундах (0, если ещё не взведён). */
uint32_t bsp_wdog_timeout_s(void);

#endif /* BSP_WDOG_H */
