/*
 * bsp_boot_state — счётчик попыток загрузки поверх SRC General Purpose
 * Register (MIMXRT1052).
 *
 * Назначение: пережить несколько сбросов подряд без реального
 * персистентного хранилища во flash. SRC_GPR — retained-регистр: сохраняет
 * значение через тёплый/watchdog-сброс, теряет его только на POR.
 *
 * Контракт: bsp_boot_state_init() сама детектирует POR по SRC->SRSR и, если
 * это POR, обнуляет счётчик — вызывающему коду не нужно проверять причину
 * сброса самостоятельно для этой цели. Причина «сброс по watchdog?» — не
 * этот модуль, см. bsp_wdog_caused_last_reset() (bsp/wdog.h): SRC->SRSR и
 * WDOG1->WRSR — разные регистры с разной семантикой очистки (WRSR
 * самоочищается на каждый сброс, SRSR — write-1-to-clear, накапливает биты
 * между сбросами без явной очистки).
 */

#ifndef BSP_BOOT_STATE_H
#define BSP_BOOT_STATE_H

#include <stdbool.h>
#include <stdint.h>

/*
 * Инициализация. Вызывать один раз, как можно раньше в main() (после
 * board_hw_init()/bsp_wdog_init()). Читает SRC->SRSR, определяет POR (бит
 * IPP_RESET_B — на MIMXRT1052 отдельного бита POR нет, эту роль играет он),
 * чистит SRSR (write-1-to-clear, иначе биты копятся между тёплыми сбросами)
 * и, если это POR, обнуляет счётчик попыток.
 *
 * Повторный вызов в той же сессии — не идемпотентен (снова прочитает и
 * очистит уже очищенный SRSR, увидит "не POR"): звать ровно один раз.
 */
void bsp_boot_state_init(void);

/* true, если последний сброс МК (на момент bsp_boot_state_init()) был POR. */
bool bsp_boot_state_was_por(void);

/* Текущее значение счётчика попыток. 0 сразу после POR. */
uint32_t bsp_boot_attempt_count(void);

/* Инкремент счётчика попыток. Звать перед каждой попыткой прыжка в образ. */
void bsp_boot_attempt_inc(void);

/*
 * Обнулить счётчик попыток. Звать при: успешной установке нового образа
 * (свежему образу — полный бюджет попыток), фолбэк-стирании зависшего слота
 * (ситуация изменилась).
 */
void bsp_boot_attempt_reset(void);

/*
 * Отметить образ здоровым — семантический алиас bsp_boot_attempt_reset() для
 * вызова из приложения (tft_app), а не из загрузчика: тот же эффект (счётчик
 * обнуляется), но имя называет намерение вызывающей стороны.
 */
void bsp_boot_health_mark(void);

#endif /* BSP_BOOT_STATE_H */
