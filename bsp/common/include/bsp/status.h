/**
 * @file  status.h
 * @brief Общий тип возврата для BSP-модулей.
 *
 * Используется модулями, операции которых могут завершиться ошибкой
 * в рантайме: uart_host, uart_iso, spi, can, usb, wdog и др.
 *
 * Не используется там, где ошибка невозможна или означает только
 * неправильную конфигурацию: tick, led, gpio (простое управление).
 *
 * PUBLIC  — если bsp_status_t есть в публичном заголовке модуля
 * PRIVATE — если bsp_status_t используется только внутри .c файлов
 * target_link_libraries(<target> PUBLIC|PRIVATE bsp_status)
 * В коде:
 *   #include "bsp/status.h"
 */

#ifndef BSP_STATUS_H
#define BSP_STATUS_H

/* -------------------------------------------------------------------------- */
/* Тип                                                                         */
/* -------------------------------------------------------------------------- */

/**
 * @brief Коды возврата BSP-модулей.
 *
 * Соглашение:
 *   BSP_OK       — операция завершена успешно.
 *   BSP_ERR_*    — операция завершена с ошибкой; подробности в имени кода.
 *
 * Значения фиксированы и не меняются: могут сохраняться в NVM / передаваться
 * по протоколу.
 */
typedef enum bsp_status_e
{
    BSP_OK = 0,       /**< Успех.                                    */
    BSP_ERR_INIT = 1, /**< Ошибка инициализации / модуль не готов.   */
    BSP_ERR_TIMEOUT = 2, /**< Истёк таймаут ожидания.                   */
    BSP_ERR_BUSY    = 3, /**< Ресурс занят.             */
    BSP_ERR_PARAM   = 4, /**< Невалидный аргумент  */
    BSP_ERR_OVERFLOW = 5, /**< Переполнение буфера, данные потеряны.     */
    BSP_ERR_NOT_SUPPORTED = 6, /**< Функция не поддерживается  */
} bsp_status_t;

#endif /* BSP_STATUS_H */